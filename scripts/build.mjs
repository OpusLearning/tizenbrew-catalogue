// Deterministic build: validates the catalogue, then writes app/ and service/ from src/ and data/.
// Same inputs always give byte-identical outputs (no timestamps).
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = process.argv[2] ? process.argv[2] : join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(dirname(fileURLToPath(import.meta.url)), '..');
const Lib = require(join(src, 'src/lib.js'));
export const HELPER_PORT = 8093;

const pkg = JSON.parse(readFileSync(join(src, 'package.json'), 'utf8'));
const cat = JSON.parse(readFileSync(join(src, 'data/catalogue.json'), 'utf8'));
const errors = Lib.validateCatalogue(cat);
if (errors.length) {
  console.error('Catalogue is invalid:\n  ' + errors.join('\n  '));
  process.exit(1);
}

rmSync(join(root, 'app'), { recursive: true, force: true });
rmSync(join(root, 'service'), { recursive: true, force: true });
mkdirSync(join(root, 'app'), { recursive: true });
mkdirSync(join(root, 'service'), { recursive: true });

const banner = `/* tizenbrew-catalogue ${pkg.version} - generated by scripts/build.mjs from src/; do not edit. */\n`;
for (const f of ['index.html', 'style.css', 'lib.js', 'tbclient.js', 'ui.js']) {
  const body = readFileSync(join(src, 'src', f), 'utf8');
  writeFileSync(join(root, 'app', f), f.endsWith('.js') || f.endsWith('.css') ? banner + body : body);
}
writeFileSync(join(root, 'app', 'catalogue.js'),
  banner +
  'window.TBCAT_BUILD = ' + JSON.stringify({ version: pkg.version }) + ';\n' +
  'window.TBCAT_DATA = ' + JSON.stringify(cat, null, 1) + ';\n');

const allowed = cat.apps.filter(a => a.kind === 'standalone').map(a => a.appId).sort();
const service = readFileSync(join(src, 'src/service.js'), 'utf8')
  .replace('__VERSION__', pkg.version)
  .replace('__PORT__', String(HELPER_PORT))
  .replace('__ALLOWED_APP_IDS__', JSON.stringify(allowed));
if (/__[A-Z_]+__/.test(service)) { console.error('Unreplaced placeholder in service'); process.exit(1); }
writeFileSync(join(root, 'service', 'service.js'), banner + service);
console.log(`built ${pkg.name} ${pkg.version}: ${cat.apps.length} entries, ${allowed.length} standalone app ids -> ${root}`);
